"""Persist transformed analytics player-season batting rows."""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import asdict

from sqlalchemy import MetaData, Table
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.engine import Connection

from app.analytics.player_season_batting_data import PlayerSeasonBatting

_METRIC_COLUMNS = (
    "games",
    "plate_appearances",
    "at_bats",
    "hits",
    "singles",
    "doubles",
    "triples",
    "home_runs",
    "walks",
    "hit_by_pitch",
    "strikeouts",
    "sacrifice_flies",
    "sacrifice_bunts",
    "batting_average",
    "on_base_percentage",
    "slugging_percentage",
    "ops",
    "strikeout_rate",
    "walk_rate",
)


def load_player_season_batting(
    connection: Connection,
    rows: Sequence[PlayerSeasonBatting],
) -> int:
    """Insert or refresh player-season batting rows.

    ``created_at`` is generated by the database on insert and is left
    unchanged on conflict. Existing ``(player_id, season_id)`` rows are
    updated to the current derived metrics. The caller owns the
    transaction.
    """
    if not rows:
        return 0

    table = _analytics_table(connection)
    statement = insert(table).values([asdict(row) for row in rows])
    statement = statement.on_conflict_do_update(
        index_elements=["player_id", "season_id"],
        set_={
            column: statement.excluded[column]
            for column in _METRIC_COLUMNS
        },
    )
    connection.execute(statement)
    return len(rows)


def _analytics_table(connection: Connection) -> Table:
    metadata = MetaData()
    return Table(
        "player_season_batting",
        metadata,
        schema="analytics",
        autoload_with=connection,
    )
