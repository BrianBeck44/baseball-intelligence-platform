"""Persist transformed analytics player-season CA-OPS rows."""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import asdict

from sqlalchemy import MetaData, Table
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.engine import Connection

from app.analytics.player_season_ca_ops_data import PlayerSeasonCaOps

_ANALYTICS_WRITE_BATCH_SIZE = 500

_METRIC_COLUMNS = (
    "plate_appearances",
    "observed_ops",
    "league_ops",
    "expected_opponent_ops",
    "ca_ops",
)


def load_player_season_ca_ops(
    connection: Connection,
    rows: Sequence[PlayerSeasonCaOps],
) -> int:
    """Insert or refresh player-season CA-OPS rows.

    ``created_at`` is generated by the database on insert and is left
    unchanged on conflict. Existing ``(player_id, season_id)`` rows are
    updated to the current derived metrics. The caller owns the
    transaction.
    """
    if not rows:
        return 0

    table = _analytics_table(connection)
    for start in range(0, len(rows), _ANALYTICS_WRITE_BATCH_SIZE):
        batch = rows[start : start + _ANALYTICS_WRITE_BATCH_SIZE]
        statement = insert(table).values([asdict(row) for row in batch])
        statement = statement.on_conflict_do_update(
            index_elements=["player_id", "season_id"],
            set_={
                column: statement.excluded[column]
                for column in _METRIC_COLUMNS
            },
        )
        connection.execute(statement)
    return len(rows)


def _analytics_table(connection: Connection) -> Table:
    metadata = MetaData()
    return Table(
        "player_season_ca_ops",
        metadata,
        schema="analytics",
        autoload_with=connection,
    )
